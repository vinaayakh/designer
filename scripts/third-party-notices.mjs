#!/usr/bin/env node
// Writes THIRD_PARTY_NOTICES.md: the licence of every third-party package built into the
// Designer binary. That is the production npm packages bundled into the web UI (plus Tabler
// icons, whose SVGs are copied in at build time), and the Go modules linked into cmd/designer.
//
//   node scripts/third-party-notices.mjs           # rewrite the file
//   node scripts/third-party-notices.mjs --check   # fail if it is out of date (CI)
import { execFileSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");
const web = join(root, "web");
const out = join(root, "THIRD_PARTY_NOTICES.md");

const licenceFile = (dir) => {
  if (!dir || !existsSync(dir)) return null;
  const f = readdirSync(dir).find((n) => /^(licen[cs]e|copying)(\.(md|txt))?$/i.test(n) || /^licen[cs]e[-.]/i.test(n));
  return f ? readFileSync(join(dir, f), "utf8").replace(/\r\n/g, "\n").trim() : null;
};

// ---- npm: production packages (not dev-only) from the lockfile, plus Tabler icons.
const lock = JSON.parse(readFileSync(join(web, "package-lock.json"), "utf8"));
const js = [];
for (const [path, p] of Object.entries(lock.packages)) {
  if (!path || p.dev) continue;
  const dir = join(web, path);
  const meta = existsSync(join(dir, "package.json")) ? JSON.parse(readFileSync(join(dir, "package.json"), "utf8")) : {};
  const name = path.replace(/^.*node_modules\//, "");
  const text = licenceFile(dir);
  const declared = p.license ?? meta.license ?? meta.licenses?.map((l) => l.type).join(" OR ");
  js.push({ name, version: p.version, licence: declared ?? spdxGuess(text), text });
}
const tabler = lock.packages["node_modules/@tabler/icons"];
js.push({ name: "@tabler/icons (icons copied into the build)", version: tabler.version, licence: tabler.license, text: licenceFile(join(web, "node_modules/@tabler/icons")) });

// ---- Go: modules linked into the binary.
const goList = execFileSync("go", ["list", "-deps", "-f", "{{if and (not .Standard) .Module}}{{.Module.Path}}\t{{.Module.Version}}\t{{.Module.Dir}}\t{{.Module.Main}}{{end}}", "./cmd/designer"], { cwd: root, encoding: "utf8" });
const seen = new Set();
const go = [];
for (const line of goList.split("\n")) {
  const [path, version, dir, main] = line.split("\t");
  if (!path || main === "true" || seen.has(path)) continue;
  seen.add(path);
  const text = licenceFile(dir);
  go.push({ name: path, version, licence: spdxGuess(text), text });
}

function spdxGuess(t) {
  if (!t) return "UNKNOWN";
  if (/Apache License[\s\S]*Version 2\.0/.test(t)) return "Apache-2.0";
  if (/Permission is hereby granted, free of charge/.test(t)) return "MIT";
  if (/Redistribution and use in source and binary forms/.test(t)) return /Neither the name/.test(t) ? "BSD-3-Clause" : "BSD-2-Clause";
  if (/Mozilla Public License,? v(ersion)?\.? ?2\.0/i.test(t)) return "MPL-2.0";
  if (/Permission to use, copy, modify, and\/or distribute/.test(t)) return "ISC";
  return "see text";
}

const sortByName = (a, b) => a.name.localeCompare(b.name);
js.sort(sortByName);
go.sort(sortByName);

const unknown = [...js, ...go].filter((p) => p.licence === "UNKNOWN");
const section = (title, list) => {
  const counts = {};
  for (const p of list) counts[p.licence] = (counts[p.licence] ?? 0) + 1;
  let s = `## ${title}\n\n${list.length} packages: ${Object.entries(counts).sort((a, b) => b[1] - a[1]).map(([l, n]) => `${l} (${n})`).join(", ")}.\n\n| Package | Version | Licence |\n|---|---|---|\n`;
  s += list.map((p) => `| ${p.name} | ${p.version} | ${p.licence} |`).join("\n") + "\n\n";
  // Each distinct licence text once, with the packages it covers.
  const byText = new Map();
  for (const p of list) {
    if (!p.text) continue;
    const k = p.text;
    if (!byText.has(k)) byText.set(k, []);
    byText.get(k).push(`${p.name}@${p.version}`);
  }
  s += `### Licence texts (${title})\n\n`;
  for (const [text, names] of byText) s += `<details><summary>${names.join(", ")}</summary>\n\n\`\`\`text\n${text}\n\`\`\`\n\n</details>\n\n`;
  const noText = list.filter((p) => !p.text);
  if (noText.length) s += `Packages that ship no licence file (their declared licence applies): ${noText.map((p) => `${p.name}@${p.version} (${p.licence})`).join(", ")}.\n\n`;
  return s;
};

const doc = `# Third-party notices

Designer is licensed under the Apache License 2.0 (see [LICENSE](LICENSE) and [NOTICE](NOTICE)). The Designer binary also contains the third-party software listed here, each under its own licence. Content credits (fonts bundled by Excalidraw, document templates, Knowledge Base sources) are in [NOTICE](NOTICE).

This file is generated by \`node scripts/third-party-notices.mjs\`; CI checks that it is current.

${section("Web UI (npm packages bundled into the binary)", js)}${section("Go modules linked into the binary", go)}`;

if (process.argv.includes("--check")) {
  const have = existsSync(out) ? readFileSync(out, "utf8").replace(/\r\n/g, "\n") : "";
  if (have !== doc) {
    console.error("THIRD_PARTY_NOTICES.md is out of date: run node scripts/third-party-notices.mjs and commit it.");
    process.exit(1);
  }
  console.log("THIRD_PARTY_NOTICES.md is current");
} else {
  writeFileSync(out, doc);
  console.log(`wrote THIRD_PARTY_NOTICES.md: ${js.length} npm packages, ${go.length} Go modules`);
}
if (unknown.length) {
  console.error(`packages with no known licence: ${unknown.map((p) => p.name).join(", ")}`);
  process.exit(1);
}
