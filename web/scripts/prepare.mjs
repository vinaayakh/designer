// Prepares self-hosted assets before a build:
// - Excalidraw fonts -> public/fonts (EXCALIDRAW_ASSET_PATH is the site root)
// - ELK's worker -> public/elk-worker.min.js (fetched only when a layout runs)
// - src/generated/icons.ts: only the Tabler SVGs mapped in kinds.yaml (ticket 016)
import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";

const here = (p) => new URL(p, import.meta.url);
rmSync(here("../public"), { recursive: true, force: true });
mkdirSync(here("../public"), { recursive: true });
cpSync(here("../node_modules/@excalidraw/excalidraw/dist/prod/fonts"), here("../public/fonts"), { recursive: true });
cpSync(here("../node_modules/elkjs/lib/elk-worker.min.js"), here("../public/elk-worker.min.js"));

const yaml = readFileSync(here("../../internal/catalog/data/kinds.yaml"), "utf8");
const names = [...new Set([...yaml.matchAll(/icon: ([a-z0-9-]+)/g)].map((m) => m[1]))].sort();
const entries = names.map((n) => {
  const svg = readFileSync(here(`../node_modules/@tabler/icons/icons/outline/${n}.svg`), "utf8")
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/\s+/g, " ")
    .trim();
  return `  ${JSON.stringify(n)}: ${JSON.stringify(svg)},`;
});
mkdirSync(here("../src/generated"), { recursive: true });
writeFileSync(
  here("../src/generated/icons.ts"),
  `// Generated by scripts/prepare.mjs from kinds.yaml. Tabler Icons (MIT).\nexport const ICONS: Record<string, string> = {\n${entries.join("\n")}\n};\n`,
);
console.log(`prepared fonts, ELK worker and ${names.length} icons`);
